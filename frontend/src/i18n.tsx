interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, params?: Record<string, string | number | null | undefined>) => string;
  display: (kind: string, value?: string | null) => string;
  formatRelativeTime: (date: string | Date | null | undefined) => string;
}

function relativeTime(locale: Locale, target: string | Date | null | undefined): string {
  return formatRelativeFromNow(target, locale);
}

const I18nContext = createContext<I18nContextValue | null>(null);

function detectInitialLocale(): Locale {
  const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (saved === "zh-CN" || saved === "en-US") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

function interpolate(template: string, params?: Record<string, string | number | null | undefined>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ""));
}

function humanize(value?: string | null): string {
  if (!value) return "";
  return value
    .replace(/_/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => detectInitialLocale());

  const setLocale = (next: Locale) => {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    setLocaleState(next);
  };

  useEffect(() => {
    document.documentElement.lang = locale === "zh-CN" ? "zh-CN" : "en";
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key, params) => {
        const dict = locale === "zh-CN" ? zh : en;
        let template = dict[key];
        if (template === undefined) {
          template = zh[key];
          if (template !== undefined && import.meta.env.DEV && locale !== "zh-CN") {
            console.warn(`[i18n] Missing translation for "${key}" in ${locale}, falling back to zh-CN`);
          }
        }
        if (template === undefined) {
          if (import.meta.env.DEV) {
            console.warn(`[i18n] Missing translation key "${key}"`);
          }
          template = key;
        }
        return interpolate(template, params);
      },
      display: (kind, rawValue) => {
        const value = rawValue ?? "";
        const labels = displayLabels[locale][kind];
        const fallback = displayLabels["zh-CN"][kind];
        if (labels?.[value]) return labels[value];
        if (fallback?.[value]) {
          if (import.meta.env.DEV && locale !== "zh-CN") {
            console.warn(`[i18n] Missing display label for ${kind}.${value} in ${locale}`);
          }
          return fallback[value];
        }
        if (import.meta.env.DEV && value) {
          console.warn(`[i18n] Unknown enum ${kind}.${value}`);
        }
        return humanize(value);
      },
      formatRelativeTime: (date) => relativeTime(locale, date)
    }),
    [locale]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used within I18nProvider");
  return value;
}

export function LanguageToggle({ compact = false }: { compact?: boolean }) {
  const { locale, setLocale, t } = useI18n();
  const next = locale === "zh-CN" ? "en-US" : "zh-CN";
  return (
    <button
      className={compact ? "btn h-10 w-10 px-0" : "btn gap-1"}
      type="button"
      onClick={() => setLocale(next)}
      title={t("language.toggle")}
      aria-label={t("language.toggle")}
    >
      <Languages size={16} />
      {!compact && <span>{t(locale === "zh-CN" ? "language.zh" : "language.en")}</span>}
    </button>
  );
}
